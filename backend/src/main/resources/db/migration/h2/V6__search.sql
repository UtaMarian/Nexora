-- Work for the search indexer, written in the same transaction as the change that caused it, so a crash can
-- never lose an update. The worker coalesces rows and always indexes the current state of the target.
CREATE TABLE search_queue (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(16) NOT NULL,             -- NODE | SUBTREE | PAGE | TEXT
    target_id   UUID        NOT NULL,             -- no foreign key: purged nodes must still reach the index
    attempts    INTEGER     NOT NULL DEFAULT 0,
    not_before  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_search_queue_due ON search_queue (kind, not_before, id);

-- Text read from each blob. Keyed by blob, because versions and copies share blobs, and kept here because OCR is
-- far slower than indexing: a rebuild of the search index never reads a document twice.
CREATE TABLE search_text (
    storage_key   VARCHAR(512) PRIMARY KEY,
    status        VARCHAR(16)  NOT NULL,          -- OK | EMPTY | REJECTED | FAILED
    body          TEXT,
    detail        VARCHAR(500),
    extracted_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_search_text_status ON search_text (status);
