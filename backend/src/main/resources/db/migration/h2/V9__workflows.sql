-- Approvals and reviews of one version of a file or list item. Names are kept alongside ids, so the record of who
-- decided what survives if the account is removed.
CREATE TABLE approval (
    id                 UUID PRIMARY KEY,
    node_id            UUID         NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    kind               VARCHAR(16)  NOT NULL,      -- APPROVAL | REVIEW
    mode               VARCHAR(16)  NOT NULL,      -- ANY | ALL | SEQUENTIAL
    title              VARCHAR(255) NOT NULL,
    message            VARCHAR(2000),
    status             VARCHAR(24)  NOT NULL,      -- PENDING | APPROVED | REJECTED | CHANGES_REQUESTED | CANCELLED
    outcome            VARCHAR(500),
    requested_by       UUID REFERENCES principal (id) ON DELETE SET NULL,
    requested_by_name  VARCHAR(255) NOT NULL,
    version_label      VARCHAR(32),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    due_at             TIMESTAMP WITH TIME ZONE,
    completed_at       TIMESTAMP WITH TIME ZONE,
    reminded_at        TIMESTAMP WITH TIME ZONE,
    lock_version       INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX ix_approval_node ON approval (node_id, status);
CREATE INDEX ix_approval_requester ON approval (requested_by, created_at);

CREATE TABLE approval_step (
    id                UUID PRIMARY KEY,
    approval_id       UUID         NOT NULL REFERENCES approval (id) ON DELETE CASCADE,
    position          INTEGER      NOT NULL,
    principal_id      UUID REFERENCES principal (id) ON DELETE SET NULL,
    principal_name    VARCHAR(255) NOT NULL,
    decision          VARCHAR(16)  NOT NULL,       -- PENDING | APPROVED | REJECTED | SKIPPED
    decided_by        UUID REFERENCES principal (id) ON DELETE SET NULL,
    decided_by_name   VARCHAR(255),
    decided_at        TIMESTAMP WITH TIME ZONE,
    comment           VARCHAR(2000)
);
CREATE INDEX ix_approval_step_approval ON approval_step (approval_id);
CREATE INDEX ix_approval_step_principal ON approval_step (principal_id, decision);

-- "When this happens, if these conditions hold, do these things" for one library or list.
CREATE TABLE workflow_rule (
    id            UUID PRIMARY KEY,
    container_id  UUID         NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    name          VARCHAR(120) NOT NULL,
    enabled       BOOLEAN      NOT NULL,
    definition    JSON         NOT NULL,
    created_by    UUID REFERENCES principal (id) ON DELETE SET NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_workflow_rule_container ON workflow_rule (container_id);

-- Changes waiting for the worker, written in the same transaction as the change.
CREATE TABLE workflow_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id      UUID        NOT NULL,
    event_type   VARCHAR(16) NOT NULL,
    actor_id     UUID,
    actor_name   VARCHAR(255),
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_workflow_event_node ON workflow_event (node_id, event_type);

CREATE TABLE workflow_run (
    id         UUID PRIMARY KEY,
    rule_id    UUID          NOT NULL REFERENCES workflow_rule (id) ON DELETE CASCADE,
    node_id    UUID,
    node_path  VARCHAR(4000),
    status     VARCHAR(16)   NOT NULL,             -- DONE | SKIPPED | FAILED
    detail     VARCHAR(1000),
    fire_key   VARCHAR(100),
    ran_at     TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_workflow_run_rule ON workflow_run (rule_id, ran_at);
CREATE INDEX ix_workflow_run_key ON workflow_run (rule_id, fire_key);
