-- Lookup columns point at another list in the same site.
ALTER TABLE column_def ADD COLUMN lookup_list_id UUID REFERENCES node (id) ON DELETE SET NULL;

-- One snapshot of a list item per save.
CREATE TABLE list_item_version (
    id          UUID PRIMARY KEY,
    item_id     UUID         NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    version     INTEGER      NOT NULL,
    title       VARCHAR(255) NOT NULL,
    metadata    JSON,
    created_by  UUID REFERENCES principal (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (item_id, version)
);

-- Email waits here, written in the same transaction as what caused it, until the mail server takes it.
CREATE TABLE mail_outbox (
    id          UUID PRIMARY KEY,
    recipient   VARCHAR(320) NOT NULL,
    subject     VARCHAR(500) NOT NULL,
    body_text   TEXT         NOT NULL,
    body_html   TEXT         NOT NULL,
    attempts    INTEGER      NOT NULL DEFAULT 0,
    not_before  TIMESTAMP WITH TIME ZONE NOT NULL,
    failed      BOOLEAN      NOT NULL DEFAULT FALSE,
    last_error  VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_mail_outbox_due ON mail_outbox (failed, not_before);

CREATE TABLE alert (
    id            UUID PRIMARY KEY,
    user_id       UUID        NOT NULL REFERENCES principal (id) ON DELETE CASCADE,
    node_id       UUID        NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    frequency     VARCHAR(16) NOT NULL,             -- IMMEDIATE | DAILY | WEEKLY
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    last_sent_at  TIMESTAMP WITH TIME ZONE,
    UNIQUE (user_id, node_id)
);
CREATE INDEX ix_alert_node ON alert (node_id);

-- Changes waiting to be matched against alerts. No foreign key: the change must outlive the node.
CREATE TABLE alert_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id      UUID          NOT NULL,
    action       VARCHAR(64)   NOT NULL,
    actor_id     UUID,
    actor_name   VARCHAR(255),
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Lines waiting for a daily or weekly summary.
CREATE TABLE alert_digest_item (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id     UUID          NOT NULL REFERENCES alert (id) ON DELETE CASCADE,
    summary      VARCHAR(1000) NOT NULL,
    path         VARCHAR(4000) NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_alert_digest_alert ON alert_digest_item (alert_id);

-- Read-only links. Only a hash of the token is kept, so the database cannot give a link away.
CREATE TABLE share_link (
    id               UUID PRIMARY KEY,
    token_hash       VARCHAR(64) NOT NULL UNIQUE,
    node_id          UUID        NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    scope            VARCHAR(16) NOT NULL,          -- ANYONE | ORGANIZATION
    expires_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    password_hash    VARCHAR(255),
    failed_attempts  INTEGER     NOT NULL DEFAULT 0,
    locked_until     TIMESTAMP WITH TIME ZONE,
    use_count        INTEGER     NOT NULL DEFAULT 0,
    last_used_at     TIMESTAMP WITH TIME ZONE,
    created_by       UUID        NOT NULL REFERENCES principal (id),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at       TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_share_link_node ON share_link (node_id);

-- Who shared what with whom. The access itself is an ordinary ACL entry; this powers "Shared with me".
CREATE TABLE share_grant (
    id            UUID PRIMARY KEY,
    node_id       UUID        NOT NULL REFERENCES node (id) ON DELETE CASCADE,
    principal_id  UUID        NOT NULL REFERENCES principal (id) ON DELETE CASCADE,
    level         VARCHAR(16) NOT NULL,
    shared_by     UUID        NOT NULL REFERENCES principal (id),
    shared_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (node_id, principal_id)
);
CREATE INDEX ix_share_grant_principal ON share_grant (principal_id, shared_at);

-- "Recent" reads a person's own audit trail.
CREATE INDEX ix_audit_actor ON audit_event (actor_id, occurred_at);
